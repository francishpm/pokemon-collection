import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const api = "https://api.tcgdex.net/v2/pt";
async function get(path) {
  const response = await fetch(`${api}/${path}`, { signal: AbortSignal.timeout(20000) });
  if (!response.ok) throw new Error(`${path}: ${response.status}`);
  return response.json();
}
const set = await get("sets/me06");
const details = [];
for (let i = 0; i < set.cards.length; i += 12) {
  details.push(...await Promise.all(set.cards.slice(i, i + 12).map(card => get(`cards/${card.id}`))));
}
const cards = details.map(card => {
  if (!card.image) throw new Error(`Missing image: ${card.id}`);
  return {
    id: card.id, name: card.name, number: card.localId, language: "PT",
    images: { small: `${card.image}/low.webp`, large: `${card.image}/high.webp` },
    supertype: card.category === "Pokemon" ? "Pokémon" : card.category,
    subtypes: [card.stage, card.suffix].filter(Boolean), rarity: card.rarity,
    nationalPokedexNumbers: card.dexId,
    set: { id: set.id, name: set.name, series: "Megaevolução", printedTotal: set.cardCount.official },
  };
});
const slots = details.flatMap(card => {
  const variants = ["normal", "reverse", "holo", "firstEdition"].filter(key => card.variants?.[key]);
  return (variants.length ? variants : ["normal"]).map(key => {
    const variant = key === "firstEdition" ? "first_edition" : key;
    return { id: `${card.id}:${variant}`, cardId: card.id, number: card.localId, name: card.name,
      image: `${card.image}/low.webp`, rarity: card.rarity, variant };
  });
});
await writeFile(new URL("src/data/delta-reign-catalog.json", root), JSON.stringify({ cards, slots }, null, 2) + "\n");
const quote = value => `'${String(value ?? "").replaceAll("'", "''")}'`;
const allow = (await readFile(new URL("scripts/sql/allow-anniversary-sets.sql", root), "utf8"))
  .replace("'me05',", "'me05', 'me06',");
const rows = slots.map((slot, index) => `(${["me06", slot.cardId, slot.variant, slot.number, slot.name,
  slot.image.replace('/low.webp', '/high.webp'), slot.rarity].map(quote).join(',')},${index})`);
await writeFile(new URL("supabase/migrations/20261114_add_delta_reign_catalog.sql", root),
  `-- Generated by scripts/generate-delta-reign.mjs from the Portuguese TCGdex catalog.\nbegin;\n${allow}\n` +
  `insert into public.master_set_catalog (set_id,card_id,variant,card_number,card_name,image_url,rarity,sort_order) values\n${rows.join(',\n')}\n` +
  `on conflict (set_id,card_id,variant) do update set card_number=excluded.card_number,card_name=excluded.card_name,image_url=excluded.image_url,rarity=excluded.rarity,sort_order=excluded.sort_order;\ncommit;\n`);
console.log(`Generated ${cards.length} cards and ${slots.length} slots`);
